const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1600,height:900}});
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8000');
  const audio = () => page.evaluate(() => { const a=document.getElementById('background-music');return {paused:a.paused,volume:a.volume,time:a.currentTime,loop:a.loop}; });
  assert.equal((await audio()).paused,true);
  await page.click('#music-settings');
  await page.waitForFunction(() => !document.getElementById('background-music').paused && document.getElementById('background-music').currentTime > .1);
  await page.waitForTimeout(1600);
  assert.equal((await audio()).loop,true);
  assert.ok(Math.abs((await audio()).volume - .2275)<.01);
  await page.click('#music-quieter');
  assert.equal(await page.locator('#music-volume-value').textContent(),'30%');
  await page.click('#music-toggle');
  assert.equal((await audio()).paused,true);
  await page.click('#music-toggle');
  await page.click('#music-close');
  await page.click('#sound-toggle');
  await page.waitForTimeout(300);
  assert.equal((await audio()).paused,true);
  assert.equal((await audio()).volume,0);
  await page.click('#sound-toggle');
  await page.waitForFunction(() => !document.getElementById('background-music').paused);
  await page.evaluate(() => {Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
  assert.equal((await audio()).paused,true);
  await page.evaluate(() => {Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(() => !document.getElementById('background-music').paused);
  assert.ok(await page.locator('#background-music').evaluate(a => a.src.endsWith('/bards-tale.mp3')));
  const pixels = () => page.locator('#title-vortex').evaluate(c => c.toDataURL());
  const first = await pixels();
  await page.waitForTimeout(150);
  assert.notEqual(await pixels(), first, 'Vortex cards move');
  assert.ok(await page.locator('.music-credit').textContent().then(t => t.includes('The Bard’s Tale')));
  await page.screenshot({path:'work/title-ambience.png'});
  await page.click('#music-settings'); await page.click('#music-toggle'); await page.reload();
  await page.click('#music-settings');
  assert.equal((await audio()).paused,true);
  assert.equal(await page.locator('#music-volume-value').textContent(),'30%');
  await page.click('#music-close');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForTimeout(100);
  const still = await pixels();
  await page.waitForTimeout(150);
  assert.equal(await pixels(), still, 'Reduced motion renders a static storm');
  await page.evaluate(() => document.getElementById('start-screen').classList.remove('active'));
  await page.emulateMedia({reducedMotion:'no-preference'});
  const offscreen = await pixels();
  await page.waitForTimeout(150);
  assert.equal(await pixels(), offscreen, 'Offscreen animation sleeps');
  assert.equal(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight),false);
  assert.deepEqual(errors,[]);
  await browser.close(); console.log('PASS music gesture, loop, fade, volume persistence, mute race, hidden-tab pause and card-back vortex');
})().catch(e=>{console.error(e);process.exit(1)});
